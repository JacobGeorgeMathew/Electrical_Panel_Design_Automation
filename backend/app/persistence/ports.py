"""Repository/storage contracts for application services and future adapters."""
from typing import Protocol

class ComponentCatalog(Protocol):
    def get_component(self,key:str)->dict|None: ...
    def search(self,q:str='',category:str|None=None,manufacturer:str|None=None,page:int=1,page_size:int=20,sort:str='code')->dict: ...
    def versions(self,key:str)->list[dict]: ...
    def accessories(self,key:str)->list[dict]: ...

class PatternLibrary(Protocol):
    def archetypes(self)->list[dict]: ...
    def template(self,code:str='DB',version_id:str|None=None)->dict: ...
    def electrical_templates(self,archetype_version_id:str)->list[dict]: ...

class RuleLibrary(Protocol):
    def rules(self)->list[dict]: ...

class CadLibrary(Protocol):
    def cad_models(self,version_id:str)->list[dict]: ...
    def asset_dto(self,row:dict,generated:bool=False)->dict: ...

class ProjectStore(Protocol):
    def get(self,key:str)->dict: ...
    def list(self,page:int=1,page_size:int=50)->list[dict]: ...
    def revisions(self,key:str)->list[dict]: ...
    def check_version(self,key:str,expected_version:int|None=None)->dict: ...

class AssetStorage(Protocol):
    def put(self,data:bytes,extension:str)->dict: ...
    def availability(self,row:dict)->str: ...

import {test, expect, openHarness, readDocument, pickComponent, drag} from './fixtures';

test('2D release, inspector and 3D input share PDM coordinates and durable undo; Save never reroutes', async ({page, projectId})=>{
  await openHarness(page,projectId);
  const base = await readDocument(page);
  await pickComponent(page,'QF001');
  const writes: string[]=[];
  page.on('request', r=>{if(r.method()!=='GET')writes.push(r.url());});
  await page.getByRole('button',{name:'layout2d',exact:true}).click();
  const footprint=page.getByRole('button',{name:'Move QF001',exact:true});
  const box=(await footprint.boundingBox())!;
  const svg=page.getByRole('region',{name:'2D layout canvas'}).locator('svg').first();
  const matrix=await svg.evaluate(e=>{const m=(e as SVGSVGElement).getScreenCTM()!;return {a:m.a,d:m.d};});
  const center={x:box.x+box.width/2,y:box.y+box.height/2};
  // Aligning to the same 5 mm grid yields X=140, Y=200 from fixture offsets.
  await page.mouse.move(center.x,center.y);await page.mouse.down();
  await page.mouse.move(center.x+(140-base.snapshots.pdm!.components[0].position.x)*matrix.a,
    center.y-(200-base.snapshots.pdm!.components[0].position.y)*matrix.d,{steps:8});
  expect((await readDocument(page)).document.document_sequence).toBe(0);
  expect(writes).toEqual([]);
  await page.mouse.up();
  await expect.poll(async()=> (await readDocument(page)).document.document_sequence).toBe(1);
  const target=(await readDocument(page)).snapshots.pdm!.components[0].position;
  expect(target).toEqual({...base.snapshots.pdm!.components[0].position,x:140,y:200});
  expect(writes.filter(u=>u.endsWith('/operations/commit'))).toHaveLength(1);
  await expect(page.getByLabel('Inspector x',{exact:true})).toHaveValue('140');
  await page.getByRole('button',{name:'Undo operation',exact:true}).click();
  await expect.poll(async()=> (await readDocument(page)).snapshots.pdm!.components[0].position).toEqual(base.snapshots.pdm!.components[0].position);
  await page.getByLabel('Inspector x',{exact:true}).fill('140');
  await page.getByLabel('Inspector x',{exact:true}).press('Enter');
  await expect.poll(async()=> (await readDocument(page)).document.document_sequence).toBe(3);
  await page.getByLabel('Inspector y',{exact:true}).fill('200');
  await page.getByLabel('Inspector y',{exact:true}).press('Enter');
  await expect.poll(async()=> (await readDocument(page)).document.document_sequence).toBe(4);
  expect((await readDocument(page)).snapshots.pdm!.components[0].position).toEqual(target);
  await page.getByRole('button',{name:'Undo operation',exact:true}).click();
  await expect.poll(async()=> (await readDocument(page)).document.document_sequence).toBe(5);
  await page.getByRole('button',{name:'Undo operation',exact:true}).click();
  await expect.poll(async()=> (await readDocument(page)).document.document_sequence).toBe(6);
  await page.getByRole('button',{name:'threeD',exact:true}).click();
  await page.getByLabel('Position X in millimeters').fill('140');
  await page.getByLabel('Position X in millimeters').press('Tab');
  await expect.poll(async()=> (await readDocument(page)).document.document_sequence).toBe(7);
  await page.getByLabel('Position Y in millimeters').fill('200');
  await page.getByLabel('Position Y in millimeters').press('Tab');
  await expect.poll(async()=> (await readDocument(page)).document.document_sequence).toBe(8);
  expect((await readDocument(page)).snapshots.pdm!.components[0].position).toEqual(target);
  await expect(page.getByLabel('Rotation Z in degrees')).toBeDisabled();
  await expect(page.getByLabel('Inspector rotation_deg')).toBeDisabled();
  const beforeDisplay=await readDocument(page);
  const writeCount=writes.length;
  await page.getByLabel('Camera orientation').selectOption('right');
  await page.getByLabel('Camera orientation').selectOption('front');
  await page.getByRole('button',{name:'Routes',exact:true}).click();
  await page.getByLabel('Hide QF001',{exact:true}).click();
  await page.getByLabel('Show QF001',{exact:true}).click();
  expect(writes).toHaveLength(writeCount);
  expect(await readDocument(page)).toEqual(beforeDisplay);
  const saved=page.waitForResponse(r=>r.url().endsWith(`/projects/${projectId}`)&&r.request().method()==='PATCH');
  await page.getByRole('button',{name:'Save draft',exact:true}).click();
  expect((await saved).status()).toBe(200);
  await expect.poll(()=>page.evaluate(()=>window.panelE2E.state().projectError)).toBeNull();
  await expect(page.getByRole('button',{name:'Save draft',exact:true})).toBeEnabled();
  await page.reload();
  await expect.poll(async()=> (await readDocument(page)).content_sha256).toBe(beforeDisplay.content_sha256);
  expect((await readDocument(page)).snapshots.pdm!.components[0].position).toEqual(target);
  expect((await readDocument(page)).snapshots.pdm!.routes).toEqual(base.snapshots.pdm!.routes);
  expect(writes.some(u=>/generate|placement\/validate|cad-jobs/.test(u))).toBe(false);
});

import {test,expect,openHarness,readDocument,pickComponent} from './fixtures';

test('catalog insertion uses exact version; removal requires reviewed dependencies and undo restores them',async({page,projectId})=>{
  await openHarness(page,projectId);
  const base=await readDocument(page);
  await page.getByRole('button',{name:'catalog',exact:true}).click();
  await page.getByLabel('Search catalog').fill('MCB_16A_1P_10KA');
  await page.getByRole('button').filter({hasText:'MCB_16A_1P_10KA'}).click();
  await expect(page.getByRole('region',{name:'Add catalog component'})).toBeVisible();
  for(const [axis,value] of Object.entries({x:'220',y:'200.25',z:'37.5'}))await page.getByLabel(`Catalog placement ${axis}`,{exact:true}).fill(value);
  await page.getByLabel('Catalog placement zone').selectOption('DIN');
  await page.getByLabel('Catalog placement rail').selectOption('rail-1');
  await page.getByRole('button',{name:'Preview catalog addition'}).click();
  await expect(page.getByRole('button',{name:'Apply catalog addition'})).toBeEnabled();
  expect(await readDocument(page)).toEqual(base);
  const proposal=await page.evaluate(()=>window.panelE2E.state().proposal);
  expect(proposal?.kind).toBe('operations');
  await page.getByRole('button',{name:'Apply catalog addition'}).click();
  await expect.poll(async()=> (await readDocument(page)).snapshots.cem!.components.length).toBe(2);
  const added=await readDocument(page), component=added.snapshots.cem!.components[1];
  expect(component.catalog_id).toBe('MCB_16A_1P_10KA');
  expect(component.component_version_id).toBeTruthy();
  expect(added.snapshots.pdm!.components[1]).toMatchObject({cem_component_id:component.id,position:{x:220,y:200.25,z:37.5}});
  expect(added.snapshots.cem!.connections).toEqual(base.snapshots.cem!.connections);
  await page.reload();
  await expect.poll(async()=> (await readDocument(page)).snapshots.cem!.components.length).toBe(2);
  await page.getByRole('button',{name:'Undo operation',exact:true}).click();
  await expect.poll(async()=> (await readDocument(page)).snapshots.cem).toEqual(base.snapshots.cem);
  await pickComponent(page,'QF001');
  await page.getByRole('button',{name:'Preview component removal'}).click();
  const deps=page.getByLabel('Removal dependencies');
  await expect(deps).toContainText('N-PE-C01');await expect(deps).toContainText('route-1');
  await expect(deps).toContainText('symbol-1');await expect(deps).toContainText('wire-1');
  const beforeRemoval=await readDocument(page);
  expect(await(await page.request.get(`/api/v1/projects/${projectId}/document`)).json()).toEqual(beforeRemoval);
  // Even the generic Apply entry point cannot bypass the explicit cascade review.
  await page.evaluate(()=>window.panelE2E.commit());
  expect(await page.evaluate(()=>window.panelE2E.state().error?.code)).toBe('CASCADE_CONFIRMATION_REQUIRED');
  expect(await readDocument(page)).toEqual(beforeRemoval);
  await page.getByRole('button',{name:'Discard proposal'}).click();
  expect(await readDocument(page)).toEqual(beforeRemoval);
  await page.getByRole('button',{name:'Preview component removal'}).click();
  await page.getByRole('button',{name:'Confirm removal and listed dependencies'}).click();
  await expect.poll(async()=> (await readDocument(page)).snapshots.cem!.components.length).toBe(0);
  const removed=await readDocument(page);
  expect(removed.snapshots.cem!.connections).toEqual([]);expect(removed.snapshots.pdm!.routes).toEqual([]);
  await page.getByRole('button',{name:'Undo operation',exact:true}).click();
  await expect.poll(async()=> (await readDocument(page)).snapshots).toEqual(beforeRemoval.snapshots);
});
